/* Build-time generator for the pitch table (plan M1.3 I92). Host tool: it uses
 * float and libm, the engine never does. Writes a C header on stdout:
 * sel_pitch_q16[c + 1200] = round(2^(c / 1200) * 65536) for c in -1200..1200,
 * the factor PITCH <cents> scales the mixer resample step by. */
#include <math.h>
#include <stdio.h>

int main(void) {
    int c;
    printf("/* Generated by tools/gen_pitch.c. Do not edit. */\n");
    printf("#ifndef SELECTA_PITCH_TABLE_H\n#define SELECTA_PITCH_TABLE_H\n\n#include <stdint.h>\n\n");
    printf("#define SEL_PITCH_MAX_CENTS 1200\n");
    printf("static const uint32_t sel_pitch_q16[2401] = {");
    for (c = -1200; c <= 1200; c++) {
        if (c > -1200) fputs(",", stdout);
        fputs((c + 1200) % 8 ? " " : "\n    ", stdout);
        printf("%lu", (unsigned long)lround(pow(2.0, c / 1200.0) * 65536.0));
    }
    printf("\n};\n\n#endif /* SELECTA_PITCH_TABLE_H */\n");
    return 0;
}
