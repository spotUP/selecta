/* Build-time generator for the DSP coefficient tables (plan M1.3 I99). Host
 * tool: it uses float and libm, the engine never does. Writes a C header on
 * stdout: one crossfeed row per supported sample rate, integer Q15.
 *   delay   14 frames at 44100 Hz, scaled with the rate, rounded
 *   lowpass one-pole a = 1 - exp(-2 pi 700 / rate) at 700 Hz
 *   bleed   -4.5 dB (10^(-4.5/20))
 *   direct  1.0 - bleed, so a mono signal keeps its level */
#include <math.h>
#include <stdio.h>

int main(void) {
    static const int rates[] = {8000, 11025, 16000, 22050, 32000, 44100, 48000, 88200, 96000};
    const double pi = 3.14159265358979323846;
    size_t i;
    printf("/* Generated by tools/gen_dsp_coef.c. Do not edit. */\n");
    printf("#ifndef SELECTA_DSP_COEF_H\n#define SELECTA_DSP_COEF_H\n\n");
    printf("/* rate, delay, lowpass, bleed, direct (field order of sel_dsp_crossfeed_coef) */\n");
    printf("static const sel_dsp_crossfeed_coef sel_dsp_crossfeed_table[] = {\n");
    for (i = 0; i < sizeof rates / sizeof rates[0]; i++) {
        double r = rates[i];
        long delay = lround(14.0 * r / 44100.0);
        long lowpass = lround((1.0 - exp(-2.0 * pi * 700.0 / r)) * 32768.0);
        long bleed = lround(pow(10.0, -4.5 / 20.0) * 32768.0);
        printf("    {%d, %ld, %ld, %ld, %ld},\n", rates[i], delay, lowpass, bleed, 32768L - bleed);
    }
    printf("};\n\n#endif\n");
    return 0;
}
