/* Build-time generator for the equal-power crossfade table (plan M1.3 I95). Host
 * tool: it uses float and libm, the engine never does. Writes a C header on stdout:
 * sel_xfade_out_q16[i] = round(cos(i / 256 * pi / 2) * 65536) for i in 0..256, the
 * gain of the outgoing song; the incoming gain is the same table read backwards
 * (sin(x) = cos(pi/2 - x)). */
#include <math.h>
#include <stdio.h>

int main(void) {
    int i;
    printf("/* Generated by tools/gen_xfade.c. Do not edit. */\n");
    printf("#ifndef SELECTA_XFADE_TABLE_H\n#define SELECTA_XFADE_TABLE_H\n\n#include <stdint.h>\n\n");
    printf("#define SEL_XFADE_STEPS 256u\n");
    printf("static const uint32_t sel_xfade_out_q16[257] = {");
    for (i = 0; i <= 256; i++) {
        if (i > 0) fputs(",", stdout);
        fputs(i % 8 ? " " : "\n    ", stdout);
        printf("%lu", (unsigned long)lround(cos(i / 256.0 * 1.57079632679489661923) * 65536.0));
    }
    printf("\n};\n\n#endif /* SELECTA_XFADE_TABLE_H */\n");
    return 0;
}
