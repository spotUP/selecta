/* Build-time generator for the visualisation tables (plan M1.3 I87). Host
 * tool: it uses float and libm, the engine never does. Writes a C header on
 * stdout: the 256-point Hann window (Q15), the FFT twiddles cos and -sin of
 * 2 pi k / 256 for k < 128 (Q15, forward transform e^-j), and the 17 band
 * edges in Hz, log spaced from 43 Hz to 16 kHz. */
#include <math.h>
#include <stdio.h>

#define N 256

static long q15(double v) {
    long r = lround(v * 32767.0);
    return r > 32767 ? 32767 : (r < -32767 ? -32767 : r);
}

static void sep(int k) {
    if (k) fputs(",", stdout);
    fputs(k % 16 ? " " : "\n    ", stdout);
}

int main(void) {
    const double pi = 3.14159265358979323846;
    int k;
    printf("/* Generated by tools/gen_viz_table.c. Do not edit. */\n");
    printf("#ifndef SELECTA_VIZ_TABLE_H\n#define SELECTA_VIZ_TABLE_H\n\n#include <stdint.h>\n\n");
    printf("static const int16_t sel_viz_hann[%d] = {", N);
    for (k = 0; k < N; k++) {
        sep(k);
        printf("%ld", q15(0.5 - 0.5 * cos(2.0 * pi * k / N)));
    }
    printf("\n};\n\nstatic const int16_t sel_viz_cos[%d] = {", N / 2);
    for (k = 0; k < N / 2; k++) {
        sep(k);
        printf("%ld", q15(cos(2.0 * pi * k / N)));
    }
    printf("\n};\n\nstatic const int16_t sel_viz_sin[%d] = {", N / 2);
    for (k = 0; k < N / 2; k++) {
        sep(k);
        printf("%ld", q15(-sin(2.0 * pi * k / N)));
    }
    printf("\n};\n\nstatic const uint16_t sel_viz_edge_hz[17] = {");
    for (k = 0; k <= 16; k++) printf("%s%ld", k ? ", " : "", lround(43.0 * pow(16000.0 / 43.0, k / 16.0)));
    printf("};\n\n#endif\n");
    return 0;
}
