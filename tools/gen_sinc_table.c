/* Build-time generator for the SINC resampler table (plan M0b I28). Host
 * tool: it uses float and libm, the engine never does. Writes a C header on
 * stdout: 256 phases x 8 taps, Q15, Hann-windowed sinc over |x| < 4. Tap k of
 * phase p weighs source frame pos + k - 3 for a sample at pos + p/256, so
 * x = (k - 3) - p/256. Each row is normalised to sum exactly 32768 by adding
 * the rounding error to its largest tap, so DC passes unchanged. */
#include <math.h>
#include <stdio.h>
#include <stdlib.h>

#define PHASES 256
#define TAPS 8

/* Windowed-sinc weight of tap k (frame pos + k - 3) for phase p. */
static double kernel(int k, int p) {
    const double pi = 3.14159265358979323846;
    double x = (double)(k - 3) - (double)p / PHASES;
    double s = x == 0.0 ? 1.0 : sin(pi * x) / (pi * x);
    double win = fabs(x) < 4.0 ? 0.5 + 0.5 * cos(pi * x / 4.0) : 0.0;
    return s * win;
}

int main(void) {
    int p, k;
    printf("/* Generated by tools/gen_sinc_table.c. Do not edit. */\n");
    printf("#ifndef SELECTA_SINC_TABLE_H\n#define SELECTA_SINC_TABLE_H\n\n");
    printf("#include <stdint.h>\n\n");
    printf("static const int32_t sel_sinc_table[%d][%d] = {\n", PHASES, TAPS);
    for (p = 0; p < PHASES; p++) {
        long w[TAPS];
        long sum = 0;
        double fsum = 0.0;
        int big = 0;
        for (k = 0; k < TAPS; k++) fsum += kernel(k, p);
        for (k = 0; k < TAPS; k++) {
            w[k] = lround(kernel(k, p) / fsum * 32768.0);
            sum += w[k];
            if (labs(w[k]) > labs(w[big])) big = k;
        }
        w[big] += 32768 - sum;
        printf("    {");
        for (k = 0; k < TAPS; k++) printf("%ld%s", w[k], k + 1 < TAPS ? ", " : "");
        printf("},\n");
    }
    printf("};\n\n#endif\n");
    return 0;
}
