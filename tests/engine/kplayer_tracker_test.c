/* I732: the native KPlayer adapter fills the tracker view. On the Amiga .mod plays under kplayer, and only the openmpt
 * and nuade adapters used to export RP_TRACKER_INFO / RP_TRACKER_CELLS, so the pattern rows stayed empty.
 * The test #includes the real adapter.c (the host build stubs the 68k call, kp_call) and registers its real plugin
 * descriptor in an engine registry, then drives the engine's own lookup: QUEUE_ADD + PLAY of a plain M.K. module,
 * then sel_engine_tracker_info / sel_engine_tracker_cells (src/engine/engine.c, the sl->rp_tracker_cells path).
 * Expected cells are those tests/m13/pattern.expected pins for libopenmpt on the same module (selecta-test-mk.mod,
 * generated by gen_testmod): period 428 = note 61, instrument 1, effect 15 param 6 on row 0; effect 12 param 48 on
 * row 8. Sentinel: sel_kplayer_tracker_calls counts the adapter's hook calls, so a replayer that answered some other
 * way (or not at all) fails the count. Argument 1: path of the M.K. module. */
#include <selecta/engine.h>
#include <selecta/host.h>
#include <selecta/plugin.h>
#include <selecta/protocol.h>
#include <selecta/replayer.h>
#include <selecta/tags.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* The replayer binary is not part of the host build: only its size is read (>= 32), never its bytes. */
uint8_t sel_kpl_code[64];
const uint32_t sel_kpl_size = 64;

#include "../../plugins/replayers/kplayer/adapter.c"

static int g_fail;

#define CHECK(c)                                        \
    do {                                                \
        if (!(c)) {                                     \
            printf("FAIL line %d: %s\n", __LINE__, #c); \
            g_fail++;                                   \
        }                                               \
    } while (0)

static const sel_tag* t_desc;

static uint32_t reg_count(void) {
    return 1u;
}

static const sel_tag* reg_get(uint32_t i) {
    return i == 0u ? t_desc : NULL;
}

static sel_engine* eng;

static void run(const char* line) {
    sel_message m;
    char pool[1536];
    if (sel_codec_decode(line, SEL_MSG_CMD, &m, pool, sizeof pool) != SEL_CODEC_OK) {
        CHECK(0);
        return;
    }
    sel_engine_send(eng, &m);
    sel_engine_pump(eng, NULL, NULL);
}

int main(int argc, char** argv) {
    sel_engine_config cfg;
    sel_rp_tracker_info info;
    sel_rp_cell cell[4];
    char line[1200];
    uint32_t calls_before, n;
    if (argc < 2) {
        printf("usage: kplayer_tracker_test <mk.mod>\n");
        return 2;
    }
    t_desc = SEL_PLUGIN_ENTRY(1);
    CHECK(t_desc != NULL);
    memset(&cfg, 0, sizeof cfg);
    cfg.registry_count = reg_count;
    cfg.registry_get = reg_get;
    eng = sel_engine_create(sel_host_default(), &cfg);
    CHECK(eng != NULL);
    snprintf(line, sizeof line, "QUEUE_ADD %s", argv[1]);
    run(line);
    run("PLAY");
    CHECK(g_owner != NULL && g_owner->playing == 1u); /* the kplayer instance holds the (stubbed) hardware */

    calls_before = sel_kplayer_tracker_calls;
    memset(&info, 0, sizeof info);
    CHECK(sel_engine_tracker_info(eng, 0, &info) == 1);
    CHECK(info.orders == 4u && info.patterns == 4u && info.rows == 64u && info.channels == 4u);
    CHECK(sel_engine_tracker_info(eng, 4, &info) == 0); /* past the order list */

    memset(cell, 0xee, sizeof cell);
    n = sel_engine_tracker_cells(eng, 0, 0, 0, 4, cell, 4);
    CHECK(n == 4u);
    CHECK(cell[0].note == 61 && cell[0].instrument == 1 && cell[0].volume == 0 && cell[0].effect == 15 &&
          cell[0].param == 6);
    CHECK(cell[1].note == 0 && cell[1].instrument == 0 && cell[1].effect == 0 && cell[1].param == 0);
    n = sel_engine_tracker_cells(eng, 0, 0, 8, 9, cell, 1);
    CHECK(n == 1u && cell[0].note == 0 && cell[0].instrument == 0 && cell[0].effect == 12 && cell[0].param == 48);
    n = sel_engine_tracker_cells(eng, 0, 0, 62, 66, cell, 4); /* rows past the pattern read as empty cells */
    CHECK(n == 4u && cell[2].note == 0 && cell[3].effect == 0);
    CHECK(sel_engine_tracker_cells(eng, 0, 4, 0, 1, cell, 1) == 0u); /* channel 4 does not exist in M.K. */
    CHECK(sel_kplayer_tracker_calls - calls_before == 6u + 0u); /* every call above reached the adapter */

    sel_engine_destroy(eng);
    if (g_fail != 0) {
        printf("kplayer_tracker: %d failures\n", g_fail);
        return 1;
    }
    printf("kplayer_tracker: ok\n");
    return 0;
}
