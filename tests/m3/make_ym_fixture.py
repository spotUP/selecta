#!/usr/bin/env python3
"""Writes tests/m3/fixtures/ym_test.ym: an uncompressed, interleaved YM5 file, 12 s at 50 Hz (600 frames) of a
steady 492 Hz square tone on channel A (period 254 at 2 MHz) with the volume held at 15. Generated, so it has no
third-party licence (row I428). usage: make_ym_fixture.py <output>"""
import struct
import sys

FRAMES = 600
CLOCK = 2000000
regs = [[0] * FRAMES for _ in range(16)]
for f in range(FRAMES):
    regs[0][f] = 254 & 0xFF   # tone A period, low
    regs[1][f] = 0            # tone A period, high
    regs[7][f] = 0x3E         # mixer: tone A on, everything else off
    regs[8][f] = 15           # volume A
head = b"YM5!LeOnArD!" + struct.pack(">IIHIHIH", FRAMES, 1, 0, CLOCK, 50, 0, 0)
text = b"Selecta test tone\0Selecta\0Generated by tests/m3/make_ym_fixture.py\0"
body = b"".join(bytes(r) for r in regs)
with open(sys.argv[1], "wb") as fh:
    fh.write(head + text + body + b"End!")
