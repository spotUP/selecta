/* POSIX plugin module loader (design 2026-10-30-plugin-loader-sdk D1, D3, D4). A module is a shared library named
 * sel_*.dylib (macOS) or sel_*.so that exports sel_plugin_entry (include/selecta/plugin.h). Search path, first hit
 * per file name wins: $SELECTA_PLUGIN_PATH (colon list), the app plugin folder (Contents/PlugIns inside a macOS
 * bundle, else <exe dir>/plugins; SELECTA_NO_APP_PLUGINS=1 skips it, I1305d), the user plugin folder (<config dir>/plugins). The Windows LoadLibrary variant
 * lands with the Windows port. */
#include <selecta/engine.h>
#include <selecta/registry.h>

#include "loader.h"

#include <dirent.h>
#include <dlfcn.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>

#ifdef __APPLE__
#define SEL_MODULE_SUFFIX ".dylib"
#else
#define SEL_MODULE_SUFFIX ".so"
#endif

#define PATH_MAX_SEL 1024
#define NAME_MAX_SEL 256

/* File names already loaded or reserved, grown on demand (I1133: a fixed 128 dropped modules once the build had more). */
static char (*g_seen)[NAME_MAX_SEL];
static unsigned g_seen_n;
static unsigned g_seen_cap;

/* Reserves `name`; 0 on out of memory. */
static int mark_seen(const char* name) {
    if (g_seen_n >= g_seen_cap) {
        unsigned cap = g_seen_cap != 0 ? g_seen_cap * 2u : 128u;
        char(*grown)[NAME_MAX_SEL] = realloc(g_seen, cap * sizeof *grown);
        if (grown == NULL) {
            return 0;
        }
        g_seen = grown;
        g_seen_cap = cap;
    }
    snprintf(g_seen[g_seen_n++], NAME_MAX_SEL, "%s", name);
    return 1;
}

static int already_seen(const char* name) {
    unsigned i;
    for (i = 0; i < g_seen_n; i++) {
        if (strcmp(g_seen[i], name) == 0) {
            return 1;
        }
    }
    return 0;
}

/* Generated by cmake/selecta_registry.cmake: the built-in module file names this build expects (NULL ended; empty for
 * SELECTA_PLUGIN_LINK=STATIC) and the build-tree folder they were written to (NULL for STATIC). */
extern const char* const sel_registry_builtin_modules[];
extern const char* const sel_registry_builtin_dir;

/* Returns 1 when the module's entry was added. */
static int load_module(const char* path, int builtin) {
    void* h = dlopen(path, RTLD_NOW | RTLD_LOCAL);
    void* sym;
    sel_plugin_entry_fn fn;
    if (h == NULL) {
        const char* e = dlerror();
        char why[400];
        snprintf(why, sizeof why, "dlopen failed: %.300s", e != NULL ? e : "unknown error");
        sel_registry_note_rejected(path, why);
        return 0;
    }
    sym = dlsym(h, "sel_plugin_entry");
    if (sym == NULL) {
        sel_registry_note_rejected(path, "no sel_plugin_entry symbol");
        dlclose(h);
        return 0;
    }
    memcpy(&fn, &sym, sizeof fn); /* object to function pointer without a pedantic cast */
    if (!(builtin ? sel_registry_add_builtin_entry(fn, path) : sel_registry_add_entry(fn, path))) {
        sel_registry_note_rejected(path, "module table full");
        dlclose(h);
        return 0;
    }
    return 1;
}

static int by_name(const void* a, const void* b) {
    return strcmp((const char*)a, (const char*)b);
}

static void scan_dir(const char* dir) {
    DIR* d = opendir(dir);
    struct dirent* de;
    char(*names)[NAME_MAX_SEL] = NULL;
    unsigned n = 0, cap = 0, i;
    size_t slen = strlen(SEL_MODULE_SUFFIX);
    if (d == NULL) {
        return;
    }
    while ((de = readdir(d)) != NULL) {
        size_t l = strlen(de->d_name);
        if (l >= sizeof names[0] || l <= slen + 4u || strncmp(de->d_name, "sel_", 4) != 0 ||
            strcmp(de->d_name + l - slen, SEL_MODULE_SUFFIX) != 0) {
            continue;
        }
        if (n >= cap) {
            char(*grown)[NAME_MAX_SEL] = realloc(names, (cap != 0 ? cap * 2u : 128u) * sizeof *grown);
            if (grown == NULL) {
                break;
            }
            names = grown;
            cap = cap != 0 ? cap * 2u : 128u;
        }
        memcpy(names[n++], de->d_name, l + 1u);
    }
    closedir(d);
    qsort(names, n, sizeof names[0], by_name);
    for (i = 0; i < n; i++) {
        char path[PATH_MAX_SEL];
        if (already_seen(names[i]) || !mark_seen(names[i])) {
            continue;
        }
        if (snprintf(path, sizeof path, "%s/%s", dir, names[i]) < (int)sizeof path) {
            load_module(path, 0);
        }
    }
    free(names);
}

/* Built-in modules (I427f): every file name this build expects is looked up in, first hit wins,
 * $SELECTA_BUILTIN_MODULES_DIR (when set it is the only folder), else the app plugin folder, then the build-tree folder
 * baked in at configure time. A name
 * that no folder yields a loadable module is reported missing; the name is marked seen so the general scan never
 * loads a second copy from a user folder. */
static void load_builtin_modules(void) {
    const char* env = getenv("SELECTA_BUILTIN_MODULES_DIR");
    char app[PATH_MAX_SEL];
    const char* dirs[3];
    unsigned nd = 0, k, i;
    if (sel_registry_builtin_modules[0] == NULL) {
        return;
    }
    if (env != NULL && *env != '\0') {
        dirs[nd++] = env; /* exclusive: an explicit folder is the whole built-in set (tests, relocated installs) */
    } else {
        if (sel_app_plugin_dir(app, sizeof app)) {
            dirs[nd++] = app;
        }
        if (sel_registry_builtin_dir != NULL) {
            dirs[nd++] = sel_registry_builtin_dir;
        }
    }
    for (k = 0; sel_registry_builtin_modules[k] != NULL; k++) {
        const char* name = sel_registry_builtin_modules[k];
        int ok = 0;
        for (i = 0; i < nd && !ok; i++) {
            char path[PATH_MAX_SEL];
            if (snprintf(path, sizeof path, "%s/%s", dirs[i], name) < (int)sizeof path && access(path, R_OK) == 0) {
                ok = load_module(path, 1);
            }
        }
        if (!ok) {
            sel_registry_note_builtin_missing(name);
        }
        mark_seen(name);
    }
}

void sel_loader_scan(void) {
    const char* env = getenv("SELECTA_PLUGIN_PATH");
    char dir[PATH_MAX_SEL];
    load_builtin_modules();
    while (env != NULL && *env != '\0') {
        const char* e = strchr(env, ':');
        size_t len = e != NULL ? (size_t)(e - env) : strlen(env);
        if (len > 0 && len < sizeof dir) {
            memcpy(dir, env, len);
            dir[len] = '\0';
            scan_dir(dir);
        }
        env = e != NULL ? e + 1 : NULL;
    }
    /* I1305d: SELECTA_NO_APP_PLUGINS=1 leaves the app plugin folder out of this general scan (the built-in set above still loads
     * from it), so a test that names its own module set in $SELECTA_PLUGIN_PATH is not joined by the CLI's full bundled folder (I1242b). */
    const char* no_app = getenv("SELECTA_NO_APP_PLUGINS");
    if ((no_app == NULL || no_app[0] != '1') && sel_app_plugin_dir(dir, sizeof dir)) {
        scan_dir(dir);
    }
    if (sel_config_dir(dir, sizeof dir - 16u)) {
        strcat(dir, "/plugins");
        scan_dir(dir);
    }
}
