#include "manifest_dump.h"

#include <selecta/plugin.h>

#include <string.h>

static void put_str(FILE* out, const char* s) {
    fputc('"', out);
    for (; *s != '\0'; s++) {
        if (*s == '"' || *s == '\\') {
            fputc('\\', out);
            fputc(*s, out);
        } else if (*s == '\n') {
            fputs("\\n", out);
        } else {
            fputc(*s, out);
        }
    }
    fputc('"', out);
}

/* One list as `static const sel_tag <name>[]`, nested lists first (as their own arrays named <name>_<n>). */
static int emit_list(FILE* out, const char* name, const sel_tag* list, const char* module, int top) {
    const sel_tag* it = list;
    const sel_tag* t;
    unsigned nested = 0;
    int have_present = 0;
    sel_tag_type ty;

    /* pass 1: nested lists and the present-pointer list */
    while ((t = sel_tag_next(&it)) != NULL) {
        if (!sel_tag_type_of(t->tag, &ty)) {
            return -1;
        }
        if (ty == SEL_TT_LIST && (const sel_tag*)t->value != NULL) {
            char sub[96];
            snprintf(sub, sizeof sub, "%s_%u", name, nested++);
            if (emit_list(out, sub, (const sel_tag*)t->value, NULL, 0) != 0) {
                return -1;
            }
        }
    }
    if (top) {
        /* the hooks live in the plugin's TAGS list: list its pointer tags by id */
        const sel_tag* hooks = (const sel_tag*)sel_tag_find(list, SEL_PLUGIN_TAGS, 0);
        const sel_tag* h = hooks;
        while ((t = sel_tag_next(&h)) != NULL) {
            if (sel_tag_type_of(t->tag, &ty) && ty == SEL_TT_PTR) {
                if (!have_present) {
                    fprintf(out, "static const sel_tag %s_present[] = {\n", name);
                    have_present = 1;
                }
                fprintf(out, "    {SEL_%s, 0},\n", sel_tag_name(t->tag));
            }
        }
    }
    if (have_present) {
        fputs("    {SEL_TAG_END, 0}};\n", out);
    }
    fprintf(out, "static const sel_tag %s[] = {\n", name);
    it = list;
    nested = 0;
    while ((t = sel_tag_next(&it)) != NULL) {
        sel_tag_type_of(t->tag, &ty);
        if (ty == SEL_TT_INT) {
            fprintf(out, "    {SEL_%s, %lu},\n", sel_tag_name(t->tag), (unsigned long)t->value);
        } else if (ty == SEL_TT_STR) {
            if (top && module != NULL && t->tag == SEL_PLUGIN_MODULE) {
                continue; /* replaced below */
            }
            fprintf(out, "    {SEL_%s, (uintptr_t)", sel_tag_name(t->tag));
            put_str(out, t->value != 0 ? (const char*)t->value : "");
            fputs("},\n", out);
        } else if (ty == SEL_TT_LIST && (const sel_tag*)t->value != NULL) {
            fprintf(out, "    {SEL_%s, (uintptr_t)%s_%u},\n", sel_tag_name(t->tag), name, nested++);
        }
    }
    if (top && module != NULL) {
        fputs("    {SEL_PLUGIN_MODULE, (uintptr_t)", out);
        put_str(out, module);
        fputs("},\n", out);
    }
    if (have_present) {
        fprintf(out, "    {SEL_PLUGIN_HOOKS_PRESENT, (uintptr_t)%s_present},\n", name);
    }
    fputs("    {SEL_TAG_END, 0}};\n", out);
    return 0;
}

int sel_manifest_dump_c(FILE* out, const sel_tag* const* descs, const char* const* modules, uint32_t count) {
    uint32_t i;
    fputs("/* Generated by selecta-cli plugins --manifest-c. Do not edit. */\n#include <selecta/plugin.h>\n\n", out);
    for (i = 0; i < count; i++) {
        char name[32];
        snprintf(name, sizeof name, "m%u", (unsigned)i);
        /* The descriptor holds its hooks under TAGS; present ids belong on the descriptor, the plugin's own list
         * is emitted by the same walk, so the present list lands next to the tags that hold the pointers. */
        if (emit_list(out, name, descs[i], modules != NULL ? modules[i] : NULL, 1) != 0) {
            return -1;
        }
        fprintf(out, "static const sel_tag* %s_entry(uint32_t host_api) {\n    (void)host_api;\n    return %s;\n}\n\n",
                name, name);
    }
    fputs("sel_plugin_entry_fn sel_manifest_entries[] = {\n", out);
    for (i = 0; i < count; i++) {
        fprintf(out, "    m%u_entry,\n", (unsigned)i);
    }
    fputs("    0};\n", out);
    return 0;
}
