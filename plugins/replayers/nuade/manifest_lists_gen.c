/* Host tool (I427e4): writes manifest_lists.h, the FORMATS and EXTENSIONS lists of the Amiga nuade manifest, from the
 * registry walk the plugin itself runs at entry (lists.c). The Amiga build cannot run the walk at configure time, so the
 * header is committed; test nuade-manifest-lists writes it again and fails when the committed copy differs.
 * Regenerate: build/host/plugins/replayers/nuade/nuade_manifest_lists plugins/replayers/nuade/manifest_lists.h
 * I1314: also SEL_NUADE_MANIFEST_SIG_NAMES, "id=Name;" for every usable player with a sure signature row, the format
 * name the scan stores for a signature hit without opening the module (manifest.c rp_scan_meta). */
#include "lists.h"
#include "signatures.h"

#include <nuade/player.h>
#include <stdio.h>
#include <string.h>

static char g_formats[SEL_NUADE_LIST_LEN];
static char g_extensions[SEL_NUADE_LIST_LEN];
static char g_names[SEL_NUADE_LIST_LEN];

/* Appends "id=Name;" once per player that owns a sure row (rows of one player are consecutive). 0 on overflow or on
 * a name holding the separators. */
static int build_sig_names(char* out) {
    size_t i, len = 0;
    const char* last = NULL;
    out[0] = '\0';
    for (i = 0; i < sel_nuade_sig_count(); i++) {
        const char* id = sel_nuade_sig_player(i);
        const NuadePlayer* p;
        int n;
        if (sel_nuade_sig_entry_unsure(i) || (last != NULL && strcmp(last, id) == 0)) {
            continue;
        }
        last = id;
        p = nuade_player_find(id);
        if (p == NULL || !sel_nuade_usable(p) || p->name == NULL || strpbrk(p->name, "=;\"\\") != NULL ||
            strstr(out, id) != NULL) {
            continue;
        }
        n = snprintf(out + len, SEL_NUADE_LIST_LEN - len, "%s=%s;", id, p->name);
        if (n < 0 || (size_t)n >= SEL_NUADE_LIST_LEN - len) {
            return 0;
        }
        len += (size_t)n;
    }
    return 1;
}

int main(int argc, char** argv) {
    FILE* f;
    if (argc != 2 || !sel_nuade_build_lists(g_formats, g_extensions) || !build_sig_names(g_names)) {
        fprintf(stderr, "usage: nuade_manifest_lists <manifest_lists.h>\n");
        return 1;
    }
    f = fopen(argv[1], "w");
    if (f == NULL) {
        return 1;
    }
    fprintf(f,
            "/* Generated by nuade_manifest_lists (manifest_lists_gen.c) from the nuade registry walk. Do not edit; the\n"
            " * nuade-manifest-lists test fails when this copy drifts from the players in third_party/nuade. */\n"
            "#ifndef SEL_NUADE_MANIFEST_LISTS_H\n#define SEL_NUADE_MANIFEST_LISTS_H\n\n"
            "#define SEL_NUADE_MANIFEST_FORMATS \"%s\"\n#define SEL_NUADE_MANIFEST_EXTENSIONS \"%s\"\n"
            "#define SEL_NUADE_MANIFEST_SIG_NAMES \"%s\"\n\n#endif\n",
            g_formats, g_extensions, g_names);
    return fclose(f) == 0 ? 0 : 1;
}
